      async def setup_rules(self, interaction: discord.Interaction):
          embed = discord.Embed(
              title="Twix Rules 📋",
              description="Thank you all for reading and respecting these rules.\nThey were established to provide the best gaming experience and were created with the aim of offering you the best competitive server.",
              color=0x5865f2,
          )
          embed.add_field(name="Discord 🔵", value="All discord related rules.", inline=False)
          embed.add_field(name="Game ⚡", value="General in-game rules.", inline=False)
          embed.add_field(name="Raid 💥", value="Raid rules.", inline=False)
          embed.add_field(name="Base 🏠", value="Base related rules.", inline=False)
          embed.add_field(name="Store 💎", value="Official store rules.", inline=False)
          embed.add_field(name="Staff 🛡️", value="Staff conduct rules.", inline=False)
          embed.set_footer(text="Powered by Twix")
          view = RulesView()
          await interaction.channel.send(embed=embed, view=view)  # type: ignore
          await interaction.response.send_message("Rules posted!", ephemeral=True)

